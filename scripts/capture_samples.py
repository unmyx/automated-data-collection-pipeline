"""Generate the deterministic sample outputs used across the documentation.

    python scripts/capture_samples.py            # write docs/samples/*
    python scripts/capture_samples.py --check    # fail if the files are stale

The script creates a throwaway ``<database>_samples`` database next to the
configured one, migrates it, runs four scripted scenarios against it, writes
normalised outputs and drops the database again. It never touches the configured
database, and the only network-capable piece (the retry sample) goes through a
mocked transport, so regenerating is offline and repeatable.

Determinism rules: the pipeline's clock is frozen, run ids are replaced with a
placeholder, timestamps are dropped from the captured tables, and the DSN is
masked. Rerun the script after a behaviour change and commit the diff - that diff
is the documentation evidence for the change.
"""

